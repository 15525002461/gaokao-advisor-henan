def list_categories() -> list[dict]:
    """返回所有分类的精简信息（用于前端下拉）"""
    return [{
        "key": k,
        "name": v["name"],
        "description": v["description"],
        "subject_recommend": v.get("subject_recommend", ""),
        "keyword_count": len(v["keywords"]),
    } for k, v in MAJOR_CATEGORIES.items()]


def get_category_keywords(category_key: str) -> list[str]:
    """获取某分类的所有专业关键词"""
    cat = MAJOR_CATEGORIES.get(category_key)
    return cat["keywords"] if cat else []


def normalize_keyword(text: str) -> str:
    """普通用户输入 → SQL 匹配关键词
    例：'计算机' → '计算机' (前缀匹配)
        '计算机科学与技术' → '计算机科学与技术' (精确)
    """
    return text.strip()


def fuzzy_match_major(user_input: str, db_majors: set[str]) -> list[str]:
    """对用户输入做模糊匹配，从数据库已有的专业名中找出最相关的

    例：用户输入"计算机" → 匹配出 ['计算机科学与技术', '软件工程', ...]
    """
    if not user_input:
        return []

    user_input = user_input.strip()
    matches = []

    # 1. 完全包含
    for m in db_majors:
        if user_input in m:
            matches.append(m)

    # 2. 反向包含（用户输入比专业名长，但专业名是用户输入的子串）
    if not matches:
        for m in db_majors:
            if m in user_input:
                matches.append(m)

    # 3. 关键词分词匹配
    if not matches:
        # 中文常见关键词
        KEYWORDS = {
            "计算机": ["计算机", "软件", "数据", "人工智能", "网络", "信息"],
            "电子": ["电子", "通信", "微电子", "光电", "集成电路"],
            "电气": ["电气", "自动化", "智能", "电机"],
            "机械": ["机械", "制造", "车辆", "工业", "智能"],
            "医学": ["医学", "临床", "口腔", "麻醉", "中医", "药学", "护理", "影像"],
            "经济": ["经济", "金融", "会计", "国贸", "商务", "贸易"],
            "管理": ["管理", "工商", "行政", "人力", "营销", "物流"],
            "法学": ["法学", "法律", "政治", "行政", "社会", "公安"],
            "教育": ["教育", "师范", "学前", "心理", "体育"],
            "文学": ["文学", "中文", "新闻", "传播", "广告", "外语", "英语", "日语", "翻译"],
            "理学": ["数学", "物理", "化学", "生物", "统计", "地理", "海洋"],
            "工程": ["土木", "建筑", "材料", "化工", "环境", "矿业", "测绘", "地质"],
        }
        for user_kw, related_kws in KEYWORDS.items():
            if user_kw in user_input:
                for r_kw in related_kws:
                    for m in db_majors:
                        if r_kw in m and m not in matches:
                            matches.append(m)

    return matches[:20]  # 限制返回数量
